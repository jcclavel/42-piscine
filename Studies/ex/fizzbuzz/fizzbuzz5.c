#include <unistd.h>

void ft_numbr(int n)
{
	if(n > 9)
		ft_numbr (n / 10);
	write(1, &"0123456789"[n%10], 1);
}

int	main(void)
{
	int	i;

	i = 1;
	while (i <= 100)
	{
		if (i % 3 == 0)
			write (1, "Fizz", 4);
		if (i % 5 == 0)
			write (1, "Buzz", 4);
		if (i % 3 && i% 5)
			ft_numbr(i);
		write (1, "\n", 1);
		i++;
	}
	return (0);
}
